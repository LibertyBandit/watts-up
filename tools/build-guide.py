"""Builds the in-program user guide.

Source:  Watts Up - User Guide.md   (edit this)
Target:  watts-up.html              (the block between the USER-GUIDE markers is regenerated)

Run from the project folder:   py -3 tools/build-guide.py
Needs:   pip install markdown

The guide is stored in the program as an inert <script type="text/html"> block. The Help button turns it into a page
in a new tab, replacing {{VERSION}} and {{DATE}} with the running program's values.
"""
import io, re, sys, os
import markdown

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'Watts Up - User Guide.md')
dst = os.path.join(root, 'watts-up.html')

md_text = io.open(src, encoding='utf-8').read()
m = re.match(r'# (.+?)\n+(.*?)\n+(## .*)', md_text, re.S)
if not m:
    sys.exit('Guide must start with "# Title", an intro line, then "## " sections.')
title, intro, rest = m.group(1), m.group(2), m.group(3)

md = markdown.Markdown(extensions=['tables', 'toc', 'sane_lists'], extension_configs={'toc': {'toc_depth': '2-3'}})
body = md.convert(rest)
toc = md.toc  # <div class="toc"><ul>...</ul></div>
intro_html = markdown.markdown(intro)

CSS = """
:root{--ink:#1d2330;--muted:#5b6475;--rule:#d5dbe6;--accent:#1f4e9c;--band:#eef2f9;--code:#eef1f6}
*{box-sizing:border-box}
body{margin:0;background:#fff;color:var(--ink);font:15px/1.55 "Segoe UI",Calibri,Arial,sans-serif}
.page{max-width:860px;margin:0 auto;padding:2.2rem 1.4rem 4rem}
h1{font-size:2rem;margin:.2rem 0 .3rem;color:var(--accent);border-bottom:3px solid var(--accent);padding-bottom:.3rem}
h2{font-size:1.4rem;margin:2.2rem 0 .6rem;color:var(--accent);border-bottom:1px solid var(--rule);padding-bottom:.2rem}
h3{font-size:1.1rem;margin:1.5rem 0 .4rem;color:#2c3e66}
p,li{margin:.4rem 0}
ul,ol{padding-left:1.4rem}
code{font:.88em Consolas,monospace;background:var(--code);padding:.05em .3em;border-radius:3px}
table{border-collapse:collapse;width:100%;margin:.8rem 0;font-size:.92rem}
th,td{border:1px solid var(--rule);padding:.35rem .55rem;vertical-align:top;text-align:left}
th{background:var(--band)}
tr{break-inside:avoid}
.intro{color:var(--muted);font-style:italic}
.toc{background:var(--band);border:1px solid var(--rule);border-radius:6px;padding:.6rem 1.2rem;margin:1.2rem 0 1.6rem}
.toc:before{content:"Contents";font-weight:700;color:var(--accent)}
.toc ul{list-style:none;margin:.2rem 0;padding-left:0}
.toc ul ul{padding-left:1.2rem;font-size:.92rem}
.toc a{color:var(--ink);text-decoration:none}
.toc a:hover{text-decoration:underline}
a{color:var(--accent)}
@media print{.page{max-width:none;padding:0}h2{break-after:avoid}h3{break-after:avoid}.toc{break-after:page}a{color:inherit;text-decoration:none}}
"""

page = f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Watts Up — User Guide v{{{{VERSION}}}}</title>
<style>{CSS}</style></head>
<body><div class="page">
<h1>{title}</h1>
<div class="intro">{intro_html}</div>
{toc}
{body}
</div></body></html>"""

if '</script' in page.lower():
    sys.exit('Guide HTML must not contain "</script".')

block = ('<!-- USER-GUIDE-BEGIN (generated by tools/build-guide.py from "Watts Up - User Guide.md"; do not edit by hand) -->\n'
         '<script type="text/html" id="user-guide-html">' + page + '</script>\n'
         '<!-- USER-GUIDE-END -->')

html = io.open(dst, encoding='utf-8', newline='').read()
nl = '\r\n' if '\r\n' in html else '\n'
block = block.replace('\n', nl)
pat = re.compile(r'<!-- USER-GUIDE-BEGIN.*?<!-- USER-GUIDE-END -->', re.S)
if pat.search(html):
    html = pat.sub(lambda _m: block, html, count=1)
else:
    anchor = '<div id="print-region"></div>'
    if anchor not in html:
        sys.exit('Anchor not found in watts-up.html')
    html = html.replace(anchor, block + nl + nl + '  ' + anchor, 1)
io.open(dst, 'w', encoding='utf-8', newline='').write(html)
print('guide embedded: %d characters' % len(page))
